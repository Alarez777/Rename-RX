//! Nautilus file-manager integration.
//!
//! Nautilus has no declarative context-menu actions like Nemo; the supported
//! route is a `nautilus-python` extension in the user's data directory. The
//! generated extension adds a top-level "Rename with Rename RX" item for any
//! selected non-directory file.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

const EXTENSION_FILE_NAME: &str = "rename-rx.py";

const EXTENSION_TEMPLATE: &str = r#"# Generated by Rename RX. Changes will be overwritten.
import os
import subprocess

from gi.repository import GObject, Nautilus

APP = __APP__


def _language():
    for name in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(name)
        if value:
            return value.split(":")[0].split("_")[0].split(".")[0].lower()
    return "en"


SPANISH = _language() == "es"
LABEL = "Renombrar con Rename RX" if SPANISH else "Rename with Rename RX"
TIP = (
    "Abrir los archivos seleccionados en Rename RX"
    if SPANISH
    else "Open the selected files in Rename RX"
)


class RenameRxExtension(GObject.GObject, Nautilus.MenuProvider):
    def get_file_items(self, files):
        if not files:
            return []

        paths = []
        for file in files:
            if file.is_directory():
                return []
            location = file.get_location()
            path = location.get_path() if location is not None else None
            if not path:
                return []
            paths.append(path)

        item = Nautilus.MenuItem(
            name="RenameRx::rename",
            label=LABEL,
            tip=TIP,
            icon="document-edit-symbolic",
        )
        item.connect("activate", self._activate, paths)
        return [item]

    def _activate(self, _menu, paths):
        subprocess.Popen([APP, *paths])
"#;

pub struct NautilusState {
    /// True when the extension on disk launches this same executable.
    pub current: bool,
}

pub fn state() -> Option<NautilusState> {
    let path = extension_path()?;
    let contents = fs::read_to_string(path).ok()?;
    let current = crate::integration::launcher()
        .and_then(|launcher| extension_contents(&launcher).ok())
        .is_some_and(|expected| contents == expected);

    Some(NautilusState { current })
}

/// Nautilus only loads Python extensions when `nautilus-python` is installed.
pub fn python_support_available() -> bool {
    static AVAILABLE: OnceLock<bool> = OnceLock::new();
    *AVAILABLE.get_or_init(detect_python_support)
}

fn detect_python_support() -> bool {
    for path in [
        "/usr/lib/nautilus/extensions-4/libnautilus-python.so",
        "/usr/lib64/nautilus/extensions-4/libnautilus-python.so",
    ] {
        if Path::new(path).is_file() {
            return true;
        }
    }

    for base in ["/usr/lib", "/usr/lib64"] {
        let Ok(entries) = fs::read_dir(base) else {
            continue;
        };
        for entry in entries.flatten() {
            if entry
                .path()
                .join("nautilus/extensions-4/libnautilus-python.so")
                .is_file()
            {
                return true;
            }
        }
    }

    false
}

pub fn install() -> Result<PathBuf, String> {
    if !python_support_available() {
        return Err(
            "Nautilus Python support is not installed. Install python3-nautilus \
             (Debian/Ubuntu) or nautilus-python (Fedora/Arch) first."
                .to_owned(),
        );
    }

    let launcher = crate::integration::launcher()
        .ok_or_else(|| "Could not locate the Rename RX executable.".to_owned())?;
    let directory = extension_directory()
        .ok_or_else(|| "Could not determine the user data directory.".to_owned())?;

    write_extension(&directory, &launcher)
}

pub fn remove() -> Result<(), String> {
    let Some(path) = extension_path() else {
        return Ok(());
    };

    match fs::remove_file(&path) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(format!("Could not remove {}: {error}", path.display())),
    }
}

fn extension_directory() -> Option<PathBuf> {
    let data_home = std::env::var_os("XDG_DATA_HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .or_else(|| {
            std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".local").join("share"))
        })?;

    Some(data_home.join("nautilus-python").join("extensions"))
}

fn extension_path() -> Option<PathBuf> {
    Some(extension_directory()?.join(EXTENSION_FILE_NAME))
}

fn write_extension(directory: &Path, launcher: &Path) -> Result<PathBuf, String> {
    let contents = extension_contents(launcher)?;
    fs::create_dir_all(directory)
        .map_err(|error| format!("Could not create {}: {error}", directory.display()))?;

    let path = directory.join(EXTENSION_FILE_NAME);
    let temporary = path.with_extension("py.tmp");

    fs::write(&temporary, contents)
        .map_err(|error| format!("Could not write {}: {error}", temporary.display()))?;

    if let Err(error) = fs::rename(&temporary, &path) {
        let _ = fs::remove_file(&temporary);
        return Err(format!("Could not install {}: {error}", path.display()));
    }

    Ok(path)
}

fn extension_contents(launcher: &Path) -> Result<String, String> {
    let path = launcher
        .to_str()
        .ok_or_else(|| "The application path is not valid UTF-8.".to_owned())?;

    if path.contains(['\n', '\r']) {
        return Err("The application path contains unsupported line breaks.".to_owned());
    }

    let quoted = serde_json::to_string(path)
        .map_err(|error| format!("Could not encode the application path: {error}"))?;

    Ok(EXTENSION_TEMPLATE.replace("__APP__", &quoted))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embeds_the_launcher_as_a_python_string() {
        let contents = extension_contents(Path::new("/tmp/Rename \"RX\".AppImage")).unwrap();

        assert!(contents.contains("APP = \"/tmp/Rename \\\"RX\\\".AppImage\""));
        assert!(!contents.contains("__APP__"));
    }

    #[test]
    fn extension_filters_directories_and_uses_the_nautilus_api() {
        let contents = extension_contents(Path::new("/tmp/rename-rx")).unwrap();

        assert!(contents.contains("Nautilus.MenuProvider"));
        assert!(contents.contains("def get_file_items(self, files):"));
        assert!(contents.contains("if file.is_directory():"));
        assert!(contents.contains("subprocess.Popen([APP, *paths])"));
        assert!(contents.contains("Renombrar con Rename RX"));
        assert!(contents.contains("Rename with Rename RX"));
    }

    #[test]
    fn writes_the_extension() {
        let directory =
            std::env::temp_dir().join(format!("rename-rx-nautilus-{}", std::process::id()));
        let _ = fs::remove_dir_all(&directory);

        let path = write_extension(&directory, Path::new("/tmp/rename-rx")).unwrap();
        let written = fs::read_to_string(&path).unwrap();

        assert_eq!(path.file_name().unwrap(), EXTENSION_FILE_NAME);
        assert!(written.contains("APP = \"/tmp/rename-rx\""));
        assert!(!directory.join("rename-rx.py.tmp").exists());

        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn rejects_line_breaks_in_the_path() {
        assert!(extension_contents(Path::new("/tmp/bad\npath")).is_err());
    }
}
